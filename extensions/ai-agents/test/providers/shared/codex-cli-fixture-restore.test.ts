import assert from 'node:assert/strict';
import { chmod, copyFile, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { createCodexCliSession } from '../../../src/providers/codex-cli.js';
import type { ChatMessage } from '../../../src/types.js';

test('CLI fixture persists separate multi-turn histories and resumes through the public history API', async (t) => {
  const cwd = await mkdtemp(path.join(tmpdir(), 'ai-agents-fixture-history-'));
  t.after(() => rm(cwd, { recursive: true, force: true }));
  const executable = path.join(cwd, 'codex');
  await copyFile(path.resolve('test/fixtures/mock-codex.cjs'), executable);
  await chmod(executable, 0o755);
  const options = { provider: 'codex' as const, backend: 'cli' as const, cwd, model: '', storagePath: cwd, codexPath: executable, approval: 'never' };
  const a = await createCodexCliSession(options);
  await writeFile(path.join(cwd, 'gui-release-thinking'), '');
  await a.run('GUI_THINKING_GATE', new AbortController().signal, () => {});
  await a.run('second turn EMIT_DIFF note.txt', new AbortController().signal, () => {});
  const id = a.sessionId!;
  assert.equal(a.latestBackendTurnId?.(), `${id}-turn-2`);
  await a.dispose();
  const b = await createCodexCliSession(options);
  await b.run('other conversation', new AbortController().signal, () => {});
  assert.notEqual(b.sessionId, id);
  await b.dispose();
  const resumed = await createCodexCliSession({ ...options, resumeId: id });
  const messages: ChatMessage[] = [];
  await resumed.loadTranscript!(message => messages.push(message));
  assert.deepEqual(messages.filter(m => m.role === 'user').map(m => m.text), ['GUI_THINKING_GATE', 'second turn EMIT_DIFF note.txt']);
  assert.ok(messages.some(m => m.meta?.type === 'thinking' && m.meta.thinkingCompleted && m.text.includes('Synthetic thinking')));
  assert.ok(messages.some(m => m.tool && m.text.includes('fixture content')));
  assert.ok(messages.some(m => m.meta?.type === 'files' && m.meta.files?.some(f => f.path === 'note.txt')));
  assert.ok(messages.some(m => m.text.includes('fixture answer 2: second turn')));
  assert.ok(!messages.some(m => m.text.includes('other conversation')));
  assert.equal(new Set(messages.map(m => m.id)).size, messages.length);
  await writeFile(path.join(cwd, 'fixture-resume-failure'), '');
  await assert.rejects(resumed.loadTranscript!(() => {}), /fixture history unavailable/);
  await rm(path.join(cwd, 'fixture-resume-failure'));
  await writeFile(path.join(cwd, 'fixture-history-incomplete'), '');
  await assert.rejects(resumed.loadTranscript!(() => {}), /ターン履歴を検証できません/);
  await resumed.dispose();
});
